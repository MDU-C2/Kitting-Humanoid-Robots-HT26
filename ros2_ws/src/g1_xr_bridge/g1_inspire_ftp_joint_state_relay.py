#!/usr/bin/env python3
"""Additional /joint_states publisher for 12 *measured* Inspire FTP hand DOFs.

The original body joint-state relay remains the sole publisher of its 29 body joints.
Mimic finger joints are generated by robot_state_publisher, not faked here.
No command DDS publisher or motor interface is used by this ROS process.
"""
import json
import socket

import rclpy
from rclpy.node import Node
from sensor_msgs.msg import JointState

from g1_ftp_hand_math import SOCKET, URDF_SUFFIXES


def get_hand_joint_measurement(path=SOCKET):
    with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.2)
        sock.connect(path)
        sock.sendall(b'{"kind":"status"}\n')
        buf = sock.makefile('rb').readline(16384)
    data = json.loads(buf)
    if data.get('ok') is not True or data.get('kind') != 'inspire_ftp_state':
        raise ValueError('Invalid Inspire FTP state socket response')
    names, q = [], []
    sides = data['hands']
    for side in ('left', 'right'):
        state = sides[side]
        if state['fresh']:
            expected = [f'{side}_{suffix}_joint' for suffix in URDF_SUFFIXES]
            if state.get('joint_names') != expected or len(state.get('joint_positions', [])) != 6:
                raise ValueError('Inspire FTP joint order mismatch')
            # No synthetic zeros for a disconnected hand.
            names += expected
            q += state['joint_positions']
    return names, q


class Relay(Node):
    def __init__(self):
        super().__init__('g1_inspire_ftp_joint_state_relay')
        self.pub = self.create_publisher(JointState, '/joint_states', 10)
        self.timer = self.create_timer(0.05, self.tick)
        self.last_error = None
        self.get_logger().warn('Inspire FTP measured joint states only. No synthetic physical hand data.')

    def tick(self):
        try:
            names, pos = get_hand_joint_measurement()
            if not names:
                raise ValueError('No fresh Inspire FTP hand feedback')
        except (OSError, ValueError, KeyError, TypeError) as exc:
            e = str(exc)
            if e != self.last_error:
                self.get_logger().warn('Hands unavailable: '+e)
                self.last_error = e
            return
        self.last_error = None
        m = JointState()
        m.header.stamp = self.get_clock().now().to_msg()
        m.name = names
        m.position = pos
        self.pub.publish(m)


def main():
    rclpy.init()
    node = Relay()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == '__main__':
    main()
